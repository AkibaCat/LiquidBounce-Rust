#!/usr/bin/env python3
"""Pin target classification to actual MC26.3 Java inheritance, never MobCategory."""
import hashlib
import json
import os
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[1]


def main():
    cache=Path(os.environ['USERPROFILE'])/'.gradle/caches'
    jars=[cache/'fabric-loom/minecraftMaven/net/minecraft/minecraft-merged-deobf/26.3/minecraft-merged-deobf-26.3.jar']
    for group in ['com.mojang','com.google.guava','com.google.code.gson','it.unimi.dsi','org.slf4j','org.joml','io.netty','org.apache.logging.log4j','org.apache.commons','org.lwjgl']:
        jars.extend((cache/'modules-2/files-2.1'/group).rglob('*.jar'))
    oracle=ROOT/'native/liquidbounce-horizon/oracles/TargetEntityFacts.java'
    out=ROOT/'research/target-entity-facts.json'
    java=ROOT.parent/'sulfur-shulker-client/.tools/java/jdk-25.0.5.1/bin/java.exe'
    result=subprocess.run([str(java),'-Duser.language=en','-Duser.country=US','-Dfile.encoding=UTF-8','--class-path',os.pathsep.join(map(str,jars)),str(oracle),str(out)],capture_output=True,text=True,encoding='utf-8',errors='replace')
    (ROOT/'build/target-entity-oracle.log').write_text(result.stdout+result.stderr,encoding='utf-8')
    if result.returncode:raise SystemExit(result.stdout+result.stderr)
    data=json.loads(out.read_text(encoding='utf-8'))
    source='// SPDX-License-Identifier: GPL-3.0-or-later\n// Actual Minecraft 26.3 EntityTypes generic classes and Java assignability.\n// Generated by scripts/update-target-entity-facts.py; LiquidBounce branch order.\nuse super::{EntityKind, Target};\npub const ENTITIES: &[(&str, EntityKind)] = &[\n'
    for row in data['entities']:
        category='None' if row['category']=='None' else 'Some(Target::'+row['category']+')'
        source+='    ("'+row['type']+'", EntityKind {living:'+str(row['living']).lower()+',attackable:'+str(row['attackable']).lower()+',category:'+category+'}),\n'
    source+='];\n'
    rust=ROOT/'native/liquidbounce-behaviors/src/targeting_facts.rs'
    rust.write_text(source,encoding='utf-8')
    subprocess.run(['rustfmt','--edition','2024',str(rust)],check=True)
    print(json.dumps({'entities':len(data['entities']),'factsSha256':hashlib.sha256(out.read_bytes()).hexdigest(),'rustSha256':hashlib.sha256(rust.read_bytes()).hexdigest()}))


if __name__=='__main__':main()
