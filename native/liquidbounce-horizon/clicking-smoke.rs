#[path = "../liquidbounce-behaviors/src/clicking.rs"]
mod clicking;
use clicking::*;

fn cooldown(ticks: f64) -> Cooldown {
    Cooldown {
        real_ticks: ticks,
        reset_ticks: 0.0,
        server_tick_speed: 1.0,
        attack_delay: 10.0,
        has_cooldown: true,
    }
}
fn constant(cps: i32) -> Settings {
    Settings {
        technique: Technique::Constant,
        cps: [cps, cps],
        item_cooldown: None,
        miss_cooldown: false,
        ..Settings::default()
    }
}

#[test]
fn source_scheduler_smoke() {
    let defaults = Clicker::default();
    assert_eq!(defaults.settings.cps, [11, 14]);
    assert_eq!(defaults.settings.item_cooldown, Some([1.0, 1.0]));
    assert_eq!(defaults.settings.max_per_tick, 2);
    assert_eq!(Settings::use_key().item_cooldown, None);
    // java.util.Random(0), generated by the JDK reference (cached Gaussian included).
    let mut random = JavaRandom::seeded(0);
    for expected in [0.730967787376657, 0.24053641567148587, 0.6374174253501083] {
        assert_eq!(random.double(), expected);
    }
    let mut random = JavaRandom::seeded(0);
    for expected in [
        0.8025330637390305,
        -0.9015460884175122,
        2.080920790428163,
        0.7637707684364894,
        0.9845745328825128,
        -1.6834122587673428,
    ] {
        assert!((random.gaussian(f64::ln) - expected).abs() < 1e-14);
    }
    // 20 CPS is one physical press per 50 ms tick, including the first tick.
    let mut plan = ClickPlan::new(JavaRandom::seeded(1), Math::default());
    let settings = constant(20);
    plan.tick(1000, settings);
    for tick in 0..20 {
        assert_eq!(plan.clicks_at(tick, settings.technique, false), 1);
    }
    assert!(plan.take(settings.technique, false));
    assert!(!plan.take(settings.technique, false));
    // A real press replaces the next planned press, without changing held state.
    plan.pressed_by_player();
    assert_eq!(plan.clicks_at(1, settings.technique, false), 0);
    plan.tick(1050, settings);
    assert_eq!(plan.clicks_at(0, settings.technique, false), 0);
    // Same-mapping synthetic clicks count against the follower's current tick,
    // then make it share the leader's future rhythm.
    let mut leader = ClickPlan::new(JavaRandom::seeded(2), Math::default());
    let mut follower = ClickPlan::new(JavaRandom::seeded(3), Math::default());
    leader.tick(2000, constant(10));
    follower.tick(2000, constant(30));
    follower.pressed_by(&leader, 2000);
    assert!(!follower.take(Technique::Constant, false));
    for tick in 1..20 {
        assert_eq!(
            follower.clicks_at(tick, Technique::Constant, false),
            leader.clicks_at(tick, Technique::Constant, false)
        );
    }
    // Cooldown enforcement adds one press exactly as the server threshold fills,
    // even if the millisecond schedule has no press in that bucket.
    let mut clicker = Clicker::new(
        Settings {
            technique: Technique::Constant,
            cps: [1, 1],
            ..Settings::default()
        },
        true,
        JavaRandom::seeded(4),
        Math::default(),
    );
    clicker.tick(3000);
    assert_eq!(
        clicker.click(|| (cooldown(9.0), 0), || true, |r| r[0], |_| {}),
        0
    );
    assert_eq!(clicker.click_amount, Some(0));
    assert!(!clicker.attack_key_down(true));
    clicker.tick(3050);
    assert_eq!(clicker.amount_at(0, cooldown(10.0)), 1);
    assert_eq!(clicker.amount_at(1, cooldown(10.0)), 0);
    assert_eq!(
        clicker.click(
            || (cooldown(10.0), 1),
            || panic!("miss cooldown must gate block"),
            |r| r[0],
            |_| {}
        ),
        0
    );
    // A rejected attempt is dropped, even if missTime clears later this tick.
    assert_eq!(
        clicker.click(|| (cooldown(10.0), 0), || true, |r| r[0], |_| {}),
        0
    );
    clicker.tick(3100);
    assert_eq!(clicker.amount_at(0, cooldown(11.0)), 0);
    assert!(clicker.attack_key_down(true));
    // Human uses the same Java Random sequence, range draw and Gaussian cache.
    // This first second vector is produced by upstream HumanClickTiming with seed 0.
    let mut human = ClickPlan::new(JavaRandom::seeded(0), Math::default());
    human.tick(0, Settings::use_key());
    let counts = (0..20)
        .map(|t| human.clicks_at(t, Technique::Human, false))
        .collect::<Vec<_>>();
    assert_eq!(
        counts,
        [1, 1, 0, 1, 0, 1, 0, 0, 0, 1, 1, 1, 1, 1, 0, 1, 1, 0, 0, 1]
    );
    // A late tick resets the combo rather than delivering the entire backlog.
    human.tick(1000, Settings::use_key());
    assert_eq!(human.combo_ms(), 0);
    assert_eq!(human.clicks_at(0, Technique::Human, false), 1);
    // At 30 CPS, maxPerTick=1 spreads presses instead of silently losing them.
    let mut limited = ClickPlan::new(JavaRandom::seeded(6), Math::default());
    limited.tick(
        0,
        Settings {
            max_per_tick: 1,
            ..constant(30)
        },
    );
    for t in 0..20 {
        assert_eq!(limited.clicks_at(t, Technique::Constant, false), 1);
    }
}
