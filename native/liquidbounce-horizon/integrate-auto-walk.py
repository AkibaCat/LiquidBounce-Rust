#!/usr/bin/env python3
"""Wire AutoWalk into the shared engine after validating every source anchor.

The default invocation commits the entire prepared plan. --check is read-only.
Only owned engine sources are changed; the native game seam is generated by
auto-walk-patch.py as part of the normal staging operation.
"""
from pathlib import Path
import argparse
import os
import tempfile

ROOT = Path(__file__).resolve().parents[2]
ENGINE = 'native/liquidbounce-horizon/engine/src/'


class Plan:
    def __init__(self):
        self.original = {}
        self.changed = {}

    def edit(self, name, old, new, count=1):
        path = ROOT / (ENGINE + name)
        if path not in self.original:
            self.original[path] = path.read_text(encoding='utf8')
            self.changed[path] = self.original[path]
        source = self.changed[path]
        found = source.count(old)
        if found != count:
            raise ValueError(f'{path}: expected {count} anchors, got {found}: {old[:100]!r}')
        self.changed[path] = source.replace(old, new)

    def commit(self):
        # Recheck after preparing every transformation, so a concurrent editor
        # cannot silently lose a change between validation and publication.
        for path, original in self.original.items():
            if path.read_text(encoding='utf8') != original:
                raise ValueError(f'{path}: changed while preparing integration')
        prepared = {}
        written = []
        try:
            for path, source in self.changed.items():
                descriptor, temporary = tempfile.mkstemp(prefix=path.name + '.autowalk-', dir=path.parent)
                prepared[path] = Path(temporary)
                with os.fdopen(descriptor, 'w', encoding='utf8', newline='\n') as stream:
                    stream.write(source)
            for path, temporary in prepared.items():
                os.replace(temporary, path)
                written.append(path)
        except BaseException:
            for path in written:
                path.write_text(self.original[path], encoding='utf8', newline='\n')
            raise
        finally:
            for temporary in prepared.values():
                temporary.unlink(missing_ok=True)


def prepare():
    p = Plan()
    p.edit('lib.rs', 'mod high_jump_runtime;', 'mod high_jump_runtime;\n#[cfg(feature = "behavior-hooks")]\nmod auto_walk_runtime;')
    p.edit('behaviors.rs', '    pub high_jump: liquidbounce_behaviors::high_jump::HighJump,', '    pub high_jump: liquidbounce_behaviors::high_jump::HighJump,\n    pub auto_walk: crate::auto_walk_runtime::AutoWalkSettings,')
    p.edit('behaviors.rs', '            "HighJump",', '            "HighJump",\n            "AutoWalk",')
    p.edit('behaviors.rs', '            high_jump: Default::default(),', '            high_jump: Default::default(),\n            auto_walk: Default::default(),')
    p.edit('behaviors.rs', '            3 => self.query_running(registry, "AntiAFK"),', '            3 => self.query_running(registry, "AntiAFK"),\n            crate::auto_walk_runtime::ROTATION_PROVIDER => self.query_running(registry, "AutoWalk"),')
    p.edit('behaviors.rs', '            ModuleCallback::OnDisabled(id) if self.query_ids.get("HighJump") == Some(&id) => {', '''            ModuleCallback::OnDisabled(id) if self.query_ids.get("AutoWalk") == Some(&id) => {
                self.auto_walk.own_target = None;
            }
            ModuleCallback::OnDisabled(id) if self.query_ids.get("HighJump") == Some(&id) => {''')

    p.edit('config.rs', 'pub use high_jump::{HighJumpSetting, serialize_high_jump};', 'pub use high_jump::{HighJumpSetting, serialize_high_jump};\n#[path = "config/auto_walk.rs"]\nmod auto_walk;\npub use auto_walk::{AutoWalkSetting, serialize_auto_walk};')
    p.edit('config.rs', '    HighJump => ("HighJump", "Movement", "highJump"),', '    HighJump => ("HighJump", "Movement", "highJump"),\n    AutoWalk => ("AutoWalk", "Player", "autoWalk"),')
    p.edit('config.rs', '    HighJump(HighJumpSetting),', '    HighJump(HighJumpSetting),\n    AutoWalk(AutoWalkSetting),', 2)
    p.edit('config.rs', '            | ModuleKind::HighJump', '            | ModuleKind::HighJump\n            | ModuleKind::AutoWalk')
    p.edit('config.rs', '        ModuleKind::HighJump => high_jump::parse_high_jump(&mut patch, &root),', '        ModuleKind::HighJump => high_jump::parse_high_jump(&mut patch, &root),\n        ModuleKind::AutoWalk => auto_walk::parse_auto_walk(&mut patch, &root),')
    p.edit('config.rs', '''        SettingChange::HighJump(value) => {
            return ApplyResult::Runtime(RuntimeRequest::HighJump(*value));
        }''', '''        SettingChange::HighJump(value) => {
            return ApplyResult::Runtime(RuntimeRequest::HighJump(*value));
        }
        SettingChange::AutoWalk(value) => {
            return ApplyResult::Runtime(RuntimeRequest::AutoWalk(value.clone()));
        }''')

    p.edit('actor.rs', '''            ModuleKind::HighJump => {
                config::serialize_high_jump(&b.high_jump, &common, format, &describe)
            }''', '''            ModuleKind::HighJump => {
                config::serialize_high_jump(&b.high_jump, &common, format, &describe)
            }
            ModuleKind::AutoWalk => {
                config::serialize_auto_walk(&b.auto_walk, &common, format, &describe)
            }''')
    p.edit('actor.rs', '            ModuleKind::HighJump => Some(self.state.behaviors.borrow().high_jump.settings.mode.tag()),', '''            ModuleKind::HighJump => Some(self.state.behaviors.borrow().high_jump.settings.mode.tag()),
            ModuleKind::AutoWalk => Some(match self.state.behaviors.borrow().auto_walk.mode.as_str() {
                "Direction" => "Direction", "Goto" => "Goto", "Follow" => "Follow", _ => "Forward",
            }),''')
    p.edit('actor.rs', '''                ApplyResult::Runtime(RuntimeRequest::HighJump(setting)) => {
                    setting.apply(&mut self.state.behaviors.borrow_mut().high_jump);
                }''', '''                ApplyResult::Runtime(RuntimeRequest::HighJump(setting)) => {
                    setting.apply(&mut self.state.behaviors.borrow_mut().high_jump);
                }
                ApplyResult::Runtime(RuntimeRequest::AutoWalk(setting)) => {
                    setting.apply(&mut self.state.behaviors.borrow_mut().auto_walk);
                }''')

    p.edit('runtime.rs', '            let derp_running = modules.query_running(&state.registry, "Derp");', '            let derp_running = modules.query_running(&state.registry, "Derp");\n            let auto_walk_running = modules.query_running(&state.registry, "AutoWalk");')
    p.edit('runtime.rs', '                        4 => derp_running,', '                        4 => derp_running,\n                        crate::auto_walk_runtime::ROTATION_PROVIDER => auto_walk_running,')
    p.edit('runtime.rs', '''                            (&mut modules.anti_afk.settings.rotations, mode)
                        } else {''', '''                            (&mut modules.anti_afk.settings.rotations, mode)
                        } else if let Some(mode) = crate::auto_walk_runtime::AutoWalkSettings::processor_mode(processor) {
                            (&mut modules.auto_walk.rotations, mode)
                        } else {''')
    p.edit('runtime.rs', '''                .no_block_interact
                .finish_retry();
        }
    }

    #[cfg(feature = "behavior-hooks")]
    fn client_directional_input''', '''                .no_block_interact
                .finish_retry();
        }
        self.auto_walk_prepare(host);
    }

    #[cfg(feature = "behavior-hooks")]
    fn world_primitives(&self, host: &dyn Host, event: &mut horizon_client::mod_api::WorldPrimitivesEvent<'_>) {
        self.auto_walk_render(host, event.partial, event.primitives);
    }

    #[cfg(feature = "behavior-hooks")]
    fn client_directional_input''')
    p.edit('runtime.rs', '''    fn client_directional_input(&self, host: &dyn Host, event: &mut ClientDirectionalInputEvent) {
        use liquidbounce_behaviors::{rotations::DirectionalInput, sprint::Source};''', '''    fn client_directional_input(&self, host: &dyn Host, event: &mut ClientDirectionalInputEvent) {
        use liquidbounce_behaviors::{rotations::DirectionalInput, sprint::Source};
        // Native navigation has just consumed the current physical input. Its
        // host calls finish before taking actor state or registry callbacks.
        if self.auto_walk_result(host) {
            let options = raw_options(host);
            let mut state = self.state();
            let id = state.behaviors.borrow().query_ids.get("AutoWalk").copied();
            if let Some(id) = id {
                log_reports(state.with_registry(options, |registry, callbacks| {
                    registry.set_enabled_sync(id, false, callbacks)
                }).map(|report| vec![report]));
            }
        }
        let auto_walk_sprint = self.auto_walk_wants_sprint(host);''')
    p.edit('runtime.rs', '''        event.sprint =
            modules
                .sprint
                .event(running, Source::Input, transformed, event.sprint, None);''', '''        if auto_walk_sprint && transformed.is_moving() && modules.query_running(&state.registry, "AutoWalk") {
            event.sprint = true;
        }
        event.sprint =
            modules
                .sprint
                .event(running, Source::Input, transformed, event.sprint, None);''')
    p.edit('runtime.rs', '''    fn client_sprint_queries(&self, host: &dyn Host, event: &mut ClientSprintQueriesEvent) {
        use liquidbounce_behaviors::{''', '''    fn client_sprint_queries(&self, host: &dyn Host, event: &mut ClientSprintQueriesEvent) {
        let auto_walk_sprint = self.auto_walk_wants_sprint(host);
        use liquidbounce_behaviors::{''')
    p.edit('runtime.rs', '''                .map_or(-1, i8::from);
            event.omnidirectional''', '''                .or_else(|| (auto_walk_sprint && modules.directional_input.is_moving()
                    && modules.query_running(&state.registry, "AutoWalk")).then_some(true))
                .map_or(-1, i8::from);
            event.omnidirectional''')
    return p


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate the complete plan without writing')
    arguments = parser.parse_args()
    plan = prepare()
    if not arguments.check:
        plan.commit()
    print(f'AutoWalk integration {"validated" if arguments.check else "applied"}: {len(plan.changed)} shared files')


if __name__ == '__main__':
    main()
