// Development-only extraction of the pinned Java 25 Character simple case mapping.
import java.nio.file.Files;
import java.nio.file.Path;
public class JavaCaseFold {
    public static void main(String[] args) throws Exception {
        StringBuilder result = new StringBuilder("// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by JavaCaseFold.java with Java " + Runtime.version() + ".\n// Simple lower(upper(codePoint)); no full or locale-sensitive case expansion.\npub const SIMPLE_FOLD: &[(u32, u32)] = &[\n");
        int count = 0;
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            if (cp >= Character.MIN_SURROGATE && cp <= Character.MAX_SURROGATE) continue;
            int folded = Character.toLowerCase(Character.toUpperCase(cp));
            if (cp != folded) {
                if (count % 6 == 0) result.append("    ");
                result.append(String.format("(0x%x, 0x%x),", cp, folded));
                result.append(++count % 6 == 0 ? "\n" : " ");
            }
        }
        result.append("\n];\n");
        Files.writeString(Path.of(args[0]), result);
        System.out.println("nonIdentityMappings=" + count);
    }
}
