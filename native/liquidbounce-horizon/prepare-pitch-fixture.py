#!/usr/bin/env python3
"""Compile the exact generated Entity turn/setXRot/client setter bodies in isolation."""
from pathlib import Path
import hashlib
import importlib.util

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent
spec = importlib.util.spec_from_file_location("pitch_patch", HERE / "pitch-patch.py")
patch = importlib.util.module_from_spec(spec)
spec.loader.exec_module(patch)
changes = {}


def replace_once(text, before, after):
    if text.count(before) != 1:
        raise ValueError(f"Expected one anchor: {before[:100]}")
    return text.replace(before, after, 1)


def edit(name, transform):
    before = changes.get(name)
    if before is None:
        before = (PROJECT / "upstream/Horizon" / name).read_text(encoding="utf-8")
    changes[name] = transform(before)


patch.apply(edit, replace_once)


def function(text, signature):
    first = text.index(signature)
    opening = text.index("{", first)
    depth = 1
    end = opening + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[first:end]


game = "crates/horizon-client/src/game/"
perspective = changes[game + "perspective.rs"]
entity = changes[game + "entity.rs"]
mob = entity[entity.index("impl Entity for Mob {"):]
output = "// Generated by prepare-pitch-fixture.py from exact transformed source.\n"
output += "// Source SHA256: " + hashlib.sha256("".join(changes[name] for name in sorted(changes)).encode()).hexdigest() + "\n"
output += '''use liquidbounce_horizon_packet_tests::{packet_bridge, packet_modules, packets};
extern crate liquidbounce_horizon_packet_tests as horizon_client;
use horizon_protocol::packets::play::{self, Serverbound as S};
#[allow(dead_code)]
#[path = "../../../../upstream/Horizon/crates/horizon-client-input/src/mouse.rs"]
mod mouse;
use mouse::Rotation;
mod exact {
use super::*;
'''
output += "\n".join(function(perspective, signature) for signature in [
    "fn native_turn_rotation(", "fn turn_rotation(", "fn rope_old_after_turn("])
output += '''
#[derive(Default)]
struct Model { previous_head_pitch: f32, head_pitch: f32 }
#[derive(Default)]
struct Game { window: bool, player: Option<()>, yaw: f32, pitch: f32, player_model: Option<Model>, sent: Vec<S> }
impl Game {
    fn native_window(&self) -> bool { self.window }
    fn send(&mut self, packet: S) { self.sent.push(packet); }
'''
output += "\n".join([
    function(changes[game + "native_hooks.rs"], "    pub(super) fn native_client_reset_pitch("),
    function(changes[game + "remote_abilities.rs"], "    pub(super) fn remote_rotation("),
    function(perspective, "    pub(super) fn snap_player_model_pitch("),
])
output += '''
}
#[derive(Default)]
struct Mob { yaw: f32, body_yaw: f32, head_yaw: f32, head_pitch: f32, previous_yaw: f32, previous_head_pitch: f32 }
impl Mob {
    fn rotation(&self) -> [f32; 2] { [self.yaw, self.head_pitch] }
'''
output += function(mob, "    fn set_rotation(")
output += "\n}\n"
output += (HERE / "packet-tests/pitch-fixture-tests.rs").read_text(encoding="utf-8")
output += "\n}\n"
destination = HERE / "packet-tests/tests/generated_pitch.rs"
if not destination.exists() or destination.read_text(encoding="utf-8") != output:
    destination.write_text(output, encoding="utf-8", newline="\n")
print(destination)
