#!/usr/bin/env python3
"""Produce immutable Java Formatter symbol data from the fixed local JDK25."""
from pathlib import Path
import argparse,hashlib,json,subprocess,shutil
ROOT=Path(__file__).resolve().parents[2];HERE=Path(__file__).resolve().parent
def main():
    p=argparse.ArgumentParser();p.add_argument('--out',required=True);args=p.parse_args();out=(ROOT/args.out).resolve()
    if (out/'report.json').exists():raise SystemExit('Refusing to overwrite evidence')
    out.mkdir(parents=True,exist_ok=True);java=ROOT.parent/'sulfur-shulker-client/.tools/java/jdk-25.0.5.1/bin/java.exe';fixture=HERE/'better-inventory-locale-fixture.java'
    run=subprocess.run([str(java),str(fixture)],cwd=ROOT,capture_output=True,text=True,encoding='utf-8')
    if run.returncode:raise RuntimeError(run.stderr)
    data=json.loads(run.stdout);(out/'oracle.json').write_text(run.stdout,encoding='utf-8')
    (HERE/'better-inventory-locale-oracle.json').write_text(run.stdout,encoding='utf-8')
    destination=ROOT/'native/liquidbounce-behaviors/src/better_inventory_locale.rs'
    source='''// SPDX-License-Identifier: GPL-3.0-or-later
//! JDK25 Java Formatter symbols for all available locales, generated by
//! generate-better-inventory-locales.py; game language never selects these.
const SYMBOLS: &[(&str,u32,u32)] = &[\n'''+''.join(f'    ("{row["locale"]}",{row["decimal"]},{row["zero"]}),\n' for row in data['rows'])+'''];

pub(super) fn localize(text:&str,locale:&str)->String {
    let locale=locale.to_ascii_lowercase().replace('_',"-");
    let mut candidate=locale.split('.').next().unwrap_or("");
    let mut symbols=(46,48);
    loop {
        if let Ok(index)=SYMBOLS.binary_search_by_key(&candidate,|entry|entry.0) {symbols=(SYMBOLS[index].1,SYMBOLS[index].2);break;}
        let Some((parent,_))=candidate.rsplit_once('-') else {break;};candidate=parent;
    }
    let (decimal,zero)=symbols;
    text.chars().map(|c|match c {
        '.'=>char::from_u32(decimal).unwrap_or('.'),
        '0'..='9'=>char::from_u32(zero+u32::from(c)-u32::from('0')).unwrap_or(c),
        _=>c,
    }).collect()
}
'''
    snapshot=out/'better_inventory_locale.rs';snapshot.write_text(source,encoding='utf-8')
    subprocess.run(['rustfmt','+stable',str(snapshot)],cwd=ROOT,check=True)
    shutil.copyfile(snapshot,destination)
    (out/'report.json').write_text(json.dumps({'passed':True,'localeRows':len(data['rows']),'systemFormatLocale':data['default'],'generatorSha256':hashlib.sha256(fixture.read_bytes()).hexdigest(),'destination':str(destination),'destinationSha256':hashlib.sha256(destination.read_bytes()).hexdigest(),'scope':'Java25 actual DecimalFormatSymbols for every available Locale and Formatter %.1f samples. Generated constants retain decimal and zero-digit symbols; native Windows GetUserDefaultLocaleName chooses the process initial system format locale.'},indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'rows':len(data['rows']),'systemLocale':data['default']}))
if __name__=='__main__':main()
