#!/usr/bin/env python3
"""Extract patched transport bodies for the independently compiled Pipe test."""
from pathlib import Path
import hashlib
import importlib.util

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent
spec = importlib.util.spec_from_file_location("packet_patch", HERE / "packet-patch.py")
packet_patch = importlib.util.module_from_spec(spec)
spec.loader.exec_module(packet_patch)
changes = {}


def replace_once(text, before, after):
    if text.count(before) != 1:
        raise ValueError(f"Expected one anchor: {before[:100]}")
    return text.replace(before, after, 1)


def edit(name, transform):
    before = changes.get(name)
    if before is None:
        before = (PROJECT / "upstream/Horizon" / name).read_text(encoding="utf-8")
    changes[name] = transform(before)


packet_patch.apply(edit, replace_once)
spec = importlib.util.spec_from_file_location("slot_patch", HERE / "slot-patch.py")
slot_patch = importlib.util.module_from_spec(spec)
spec.loader.exec_module(slot_patch)
slot_patch.apply(edit, replace_once)
network = changes["crates/horizon-client/src/net.rs"]


def function(signature):
    first = network.index(signature)
    opening = network.index("{", first)
    depth = 1
    end = opening + 1
    # Selected exact-source bodies contain no braces in string literals.
    while depth:
        depth += (network[end] == "{") - (network[end] == "}")
        end += 1
    return network[first:end]


methods = "\n".join(function(signature) for signature in ["    pub fn send(&self,", "    pub fn send_silently(&self,", "    fn send_with_path(&self,"])
receive = function("fn receive_play(")
template = (HERE / "packet-tests/transport-fixture-template.rs").read_text(encoding="utf-8")
output = "// Generated by prepare-packet-fixture.py from exact patched net.rs.\n"
output += f"// patchedNetSha256={hashlib.sha256(network.encode()).hexdigest()}\n"
output += template.replace("/* GENERATED_SESSION_METHODS */", methods).replace("/* GENERATED_RECEIVE_PLAY */", receive)
destination = HERE / "packet-tests/tests/generated_transport.rs"
destination.parent.mkdir(parents=True, exist_ok=True)
if not destination.exists() or destination.read_text(encoding="utf-8") != output:
    destination.write_text(output, encoding="utf-8", newline="\n")
print(destination)
